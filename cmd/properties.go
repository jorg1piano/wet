package cmd

import (
	"fmt"
	"os"
	"strconv"
	"strings"
	"unicode/utf16"
	"unicode/utf8"
)

// EncodeProperties writes Java properties without shell quoting. ASCII output
// with Unicode escapes works with both Properties.load(InputStream) and Reader.
func EncodeProperties(pairs []EnvPair) (string, error) {
	var b strings.Builder
	b.WriteString("# Generated by wet. Do not edit. Change outputs: in .wet.yaml.\n")
	for _, p := range pairs {
		if !utf8.ValidString(p.Key) || !utf8.ValidString(p.Value) {
			return "", fmt.Errorf("property %q contains invalid UTF-8", p.Key)
		}
		b.WriteString(escapeProperty(p.Key, true))
		b.WriteByte('=')
		b.WriteString(escapeProperty(p.Value, false))
		b.WriteByte('\n')
	}
	return b.String(), nil
}

func escapeProperty(value string, key bool) string {
	var b strings.Builder
	for i, r := range value {
		switch r {
		case '\\':
			b.WriteString(`\\`)
		case '\n':
			b.WriteString(`\n`)
		case '\r':
			b.WriteString(`\r`)
		case '\t':
			b.WriteString(`\t`)
		case '\f':
			b.WriteString(`\f`)
		case ' ', '=', ':', '#', '!':
			if key || (r == ' ' && i == 0) {
				b.WriteByte('\\')
			}
			b.WriteRune(r)
		default:
			if r < 0x20 || r > 0x7e {
				for _, unit := range utf16.Encode([]rune{r}) {
					fmt.Fprintf(&b, `\u%04x`, unit)
				}
			} else {
				b.WriteRune(r)
			}
		}
	}
	return b.String()
}

// ParsePropertiesFile reads Java's byte-stream properties format. It is used
// by env push and by worktrees reading the main checkout's generated files.
func ParsePropertiesFile(path string) (map[string]string, []string, error) {
	data, err := os.ReadFile(path)
	if err != nil {
		return nil, nil, err
	}
	// Properties.load(InputStream) interprets unescaped bytes as ISO-8859-1.
	runes := make([]rune, len(data))
	for i, b := range data {
		runes[i] = rune(b)
	}
	body := strings.ReplaceAll(strings.ReplaceAll(string(runes), "\r\n", "\n"), "\r", "\n")
	lines := strings.Split(body, "\n")
	values := map[string]string{}
	var order []string
	for i := 0; i < len(lines); i++ {
		line := strings.TrimLeft(lines[i], " \t\f")
		if line == "" || line[0] == '#' || line[0] == '!' {
			continue
		}
		for {
			slashes := len(line) - len(strings.TrimRight(line, `\`))
			if slashes%2 == 0 {
				break
			}
			line = line[:len(line)-1]
			if i+1 == len(lines) {
				break
			}
			i++
			line += strings.TrimLeft(lines[i], " \t\f")
		}
		end := 0
		for end < len(line) {
			if line[end] == '\\' {
				end += 2
				continue
			}
			if strings.ContainsRune("=: \t\f", rune(line[end])) {
				break
			}
			end++
		}
		end = min(end, len(line))
		rest := strings.TrimLeft(line[end:], " \t\f")
		if len(rest) > 0 && (rest[0] == '=' || rest[0] == ':') {
			rest = rest[1:]
		}
		rest = strings.TrimLeft(rest, " \t\f")
		key, keyErr := unescapeProperty(line[:end])
		value, valueErr := unescapeProperty(rest)
		if keyErr != nil || valueErr != nil {
			// Do not print the line, which can contain a password.
			return nil, nil, fmt.Errorf("%s:%d: invalid Unicode escape in property", path, i+1)
		}
		if _, exists := values[key]; !exists {
			order = append(order, key)
		}
		values[key] = value
	}
	return values, order, nil
}

func unescapeProperty(value string) (string, error) {
	var units []uint16
	runes := []rune(value)
	for i := 0; i < len(runes); i++ {
		r := runes[i]
		if r == '\\' && i+1 < len(runes) {
			i++
			r = runes[i]
			switch r {
			case 'n':
				r = '\n'
			case 'r':
				r = '\r'
			case 't':
				r = '\t'
			case 'f':
				r = '\f'
			case 'u':
				if i+4 >= len(runes) {
					return "", fmt.Errorf("short Unicode escape")
				}
				n, err := strconv.ParseUint(string(runes[i+1:i+5]), 16, 16)
				if err != nil {
					return "", err
				}
				units = append(units, uint16(n))
				i += 4
				continue
			}
		}
		units = append(units, utf16.Encode([]rune{r})...)
	}
	return string(utf16.Decode(units)), nil
}

func parseOutputValues(path, format string) (map[string]string, []string, error) {
	if format == OutputFormatProperties {
		return ParsePropertiesFile(path)
	}
	return ParseEnvFile(path)
}
